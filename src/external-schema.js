/**
 * @file Final schema for external backends (PostgreSQL / MySQL).
 *
 * External databases start empty, so they get one current schema instead of replaying the
 * historical SQLite migrations. Keep this in sync with schema/*.sql when adding tables/columns.
 */

function postgres() {
  return [
    `CREATE TABLE IF NOT EXISTS meta ("key" TEXT PRIMARY KEY, "value" TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS settings ("key" TEXT PRIMARY KEY, "value" TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS accounts (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label TEXT NOT NULL UNIQUE,
      profile_dir TEXT NOT NULL,
      port INTEGER NOT NULL,
      friend TEXT NOT NULL DEFAULT '',
      enabled INTEGER NOT NULL DEFAULT 1,
      display_name TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS pools (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      keyword TEXT NOT NULL,
      enabled INTEGER NOT NULL DEFAULT 1,
      sort INTEGER NOT NULL DEFAULT 0
    )`,
    `CREATE TABLE IF NOT EXISTS bands (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      start_min INTEGER NOT NULL,
      end_min INTEGER NOT NULL,
      min_count INTEGER NOT NULL DEFAULT 1,
      max_count INTEGER NOT NULL DEFAULT 3,
      sort INTEGER NOT NULL DEFAULT 0
    )`,
    `CREATE TABLE IF NOT EXISTS plans (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      day TEXT NOT NULL,
      times_json TEXT NOT NULL DEFAULT '[]',
      done_json TEXT NOT NULL DEFAULT '[]',
      skipped INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      failed_json TEXT NOT NULL DEFAULT '[]',
      UNIQUE (account_id, day)
    )`,
    `CREATE TABLE IF NOT EXISTS sends (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      ts TEXT NOT NULL,
      bucket TEXT NOT NULL DEFAULT '',
      title TEXT NOT NULL DEFAULT '',
      author TEXT NOT NULL DEFAULT '',
      likes INTEGER NOT NULL DEFAULT 0,
      friend TEXT NOT NULL DEFAULT '',
      ok INTEGER NOT NULL DEFAULT 0,
      toast TEXT NOT NULL DEFAULT '',
      shot TEXT,
      video_id TEXT,
      day TEXT NOT NULL,
      source TEXT NOT NULL DEFAULT 'pool'
    )`,
    `CREATE INDEX IF NOT EXISTS idx_sends_day ON sends(day)`,
    `CREATE INDEX IF NOT EXISTS idx_sends_account ON sends(account_id, ts)`,
    `CREATE TABLE IF NOT EXISTS events (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ts TEXT NOT NULL,
      event TEXT NOT NULL,
      payload TEXT NOT NULL DEFAULT '{}'
    )`,
    `CREATE INDEX IF NOT EXISTS idx_events_ts ON events(ts)`,
    `CREATE TABLE IF NOT EXISTS friends (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      enabled INTEGER NOT NULL DEFAULT 1,
      sort INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      userid TEXT NOT NULL DEFAULT '',
      UNIQUE (account_id, name)
    )`,
    `CREATE TABLE IF NOT EXISTS account_settings (
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      value TEXT NOT NULL,
      updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (account_id, name)
    )`,
    `CREATE TABLE IF NOT EXISTS account_pools (
      account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      pool_id INTEGER NOT NULL REFERENCES pools(id) ON DELETE CASCADE,
      enabled INTEGER NOT NULL DEFAULT 1,
      PRIMARY KEY (account_id, pool_id)
    )`,
    `CREATE TABLE IF NOT EXISTS pool_hierarchy (
      pool_id INTEGER PRIMARY KEY REFERENCES pools(id) ON DELETE CASCADE,
      parent_id INTEGER NOT NULL REFERENCES pools(id) ON DELETE CASCADE
    )`,
  ];
}

function mysql() {
  return [
    'CREATE TABLE IF NOT EXISTS meta (`key` VARCHAR(128) PRIMARY KEY, `value` TEXT NOT NULL) ENGINE=InnoDB',
    'CREATE TABLE IF NOT EXISTS settings (`key` VARCHAR(128) PRIMARY KEY, `value` TEXT NOT NULL) ENGINE=InnoDB',
    `CREATE TABLE IF NOT EXISTS accounts (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      label VARCHAR(255) NOT NULL UNIQUE,
      profile_dir TEXT NOT NULL,
      port INT NOT NULL,
      friend TEXT NOT NULL,
      enabled TINYINT NOT NULL DEFAULT 1,
      display_name VARCHAR(255) NOT NULL DEFAULT '',
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS pools (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      name VARCHAR(255) NOT NULL UNIQUE,
      keyword TEXT NOT NULL,
      enabled TINYINT NOT NULL DEFAULT 1,
      sort INT NOT NULL DEFAULT 0
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS bands (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      account_id INT NOT NULL,
      name VARCHAR(255) NOT NULL,
      start_min INT NOT NULL,
      end_min INT NOT NULL,
      min_count INT NOT NULL DEFAULT 1,
      max_count INT NOT NULL DEFAULT 3,
      sort INT NOT NULL DEFAULT 0,
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS plans (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      account_id INT NOT NULL,
      day VARCHAR(16) NOT NULL,
      times_json TEXT NOT NULL,
      done_json TEXT NOT NULL,
      skipped TINYINT NOT NULL DEFAULT 0,
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      failed_json TEXT NOT NULL,
      UNIQUE KEY uniq_plan (account_id, day),
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS sends (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      account_id INT NOT NULL,
      ts VARCHAR(40) NOT NULL,
      bucket VARCHAR(255) NOT NULL DEFAULT '',
      title TEXT NOT NULL,
      author TEXT NOT NULL,
      likes INT NOT NULL DEFAULT 0,
      friend VARCHAR(255) NOT NULL DEFAULT '',
      ok TINYINT NOT NULL DEFAULT 0,
      toast TEXT NOT NULL,
      shot TEXT,
      video_id VARCHAR(64),
      day VARCHAR(16) NOT NULL,
      source VARCHAR(16) NOT NULL DEFAULT 'pool',
      INDEX idx_sends_day (day),
      INDEX idx_sends_account (account_id, ts),
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS events (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      ts VARCHAR(40) NOT NULL,
      event VARCHAR(255) NOT NULL,
      payload TEXT NOT NULL,
      INDEX idx_events_ts (ts)
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS friends (
      id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      account_id INT NOT NULL,
      name VARCHAR(255) NOT NULL,
      enabled TINYINT NOT NULL DEFAULT 1,
      sort INT NOT NULL DEFAULT 0,
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      userid VARCHAR(64) NOT NULL DEFAULT '',
      UNIQUE KEY uniq_friend (account_id, name),
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS account_settings (
      account_id INT NOT NULL,
      name VARCHAR(64) NOT NULL,
      value TEXT NOT NULL,
      updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (account_id, name),
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS account_pools (
      account_id INT NOT NULL,
      pool_id INT NOT NULL,
      enabled TINYINT NOT NULL DEFAULT 1,
      PRIMARY KEY (account_id, pool_id),
      FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
      FOREIGN KEY (pool_id) REFERENCES pools(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
    `CREATE TABLE IF NOT EXISTS pool_hierarchy (
      pool_id INT PRIMARY KEY,
      parent_id INT NOT NULL,
      FOREIGN KEY (pool_id) REFERENCES pools(id) ON DELETE CASCADE,
      FOREIGN KEY (parent_id) REFERENCES pools(id) ON DELETE CASCADE
    ) ENGINE=InnoDB`,
  ];
}

function statements(driver) {
  if (driver === 'postgres') return postgres();
  if (driver === 'mysql') return mysql();
  return [];
}

function marker(driver) {
  if (driver === 'postgres') {
    return `INSERT INTO meta ("key", "value") VALUES ('schema:external-v1', 'external-v1') ON CONFLICT ("key") DO NOTHING`;
  }
  return 'INSERT IGNORE INTO meta (`key`, `value`) VALUES (\'schema:external-v1\', \'external-v1\')';
}

function ensureSchema(conn, driver) {
  for (const sql of statements(driver)) conn.exec(sql);
  conn.exec(marker(driver));
}

module.exports = { postgres, mysql, statements, ensureSchema, marker };
